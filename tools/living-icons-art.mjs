// Generates ios/LivingSettingsIcons/Sources/LivingIconArtworkFiles.swift: the Living Icons' glyph data — the
// prototype's icon files (prototype/assets/icons/*.svg, Telegram's own glyphs at Telegram-iOS f1dd7a2), element
// by element as parse() reads them.
// usage: node tools/living-icons-art.mjs > ios/LivingSettingsIcons/Sources/LivingIconArtworkFiles.swift
import { readFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

const ICONS = fileURLToPath(new URL('../prototype/assets/icons/', import.meta.url));

// Every file a rig cuts (living-icons.js RIGS: `parts`, or `build(c)` reading c.pieces).
const FILES = [
  ['ic-bell', 'bell'], ['ic-phone', 'phone'], ['ic-folder', 'folder'], ['ic-data', 'data'], ['ic-devices', 'devices'],
  ['ic-proxy', 'proxy'], ['ic-stars', 'stars'], ['ic-premium', 'premium'], ['ic-power', 'power'], ['ic-language', 'language'],
  ['ic-gift', 'gift'], ['ic-business', 'business'], ['ic-ask', 'ask'], ['ic-faq', 'faq'], ['ic-features', 'features'],
  ['ic-appearance', 'appearance'], ['set-emoji-status', 'setEmojiStatus'], ['set-avatar', 'setAvatar'], ['set-covercolor', 'setCoverColor'],
];

const attr = (tag, name) => { const m = tag.match(new RegExp(`\\s${name}="([^"]*)"`)); return m ? m[1] : null; };
function svgSources(name) {
  const text = readFileSync(`${ICONS}${name}.svg`, 'utf8');
  const gTag = (text.match(/<g\b[^>]*>/) || [''])[0];
  const lines = [];
  for (const m of text.matchAll(/<(path|circle|ellipse)\b[^>]*>/g)) {
    const tag = m[0];
    const fill = attr(tag, 'fill') ?? attr(gTag, 'fill');
    const stroke = attr(tag, 'stroke') ?? attr(gTag, 'stroke');
    const stroked = !!stroke && fill === 'none';
    const sw = attr(tag, 'stroke-width') ?? attr(gTag, 'stroke-width') ?? '1.6';
    let geo;
    if (m[1] === 'path') geo = `.path("${attr(tag, 'd').trim().replace(/\s+/g, ' ')}")`;
    else if (m[1] === 'circle') geo = `.circle(cx: ${attr(tag, 'cx')}, cy: ${attr(tag, 'cy')}, r: ${attr(tag, 'r')})`;
    else geo = `.ellipse(cx: ${attr(tag, 'cx')}, cy: ${attr(tag, 'cy')}, rx: ${attr(tag, 'rx')}, ry: ${attr(tag, 'ry')})`;
    const opts = [];
    if (attr(tag, 'fill-rule') === 'evenodd') opts.push('evenOdd: true');
    if (stroked) opts.push(`stroke: ${sw}`);
    if (attr(tag, 'stroke-linecap') === 'round') opts.push('roundCap: true');
    lines.push(`        LivingIconSource(${geo}${opts.length ? ', ' + opts.join(', ') : ''}),`);
  }
  return lines;
}

const out = [];
out.push(`import Foundation

// The Settings glyphs of the Living Icons, generated by tools/living-icons-art.mjs (do not edit by hand): the
// prototype's icon files (prototype/assets/icons/<name>.svg) — Telegram's own glyphs at Telegram-iOS f1dd7a2,
// converted from the Images.xcassets PDFs — element by element in file order (path data verbatim, fill rule,
// stroke), as the prototype's parse() reads them. (Lock, My Profile and Saved Messages, also Telegram's, are
// rebuilt as parts in LivingIconArtwork; Money is the row's own image.)

enum LivingIconArtworkFiles {
    /// The files by the prototype's name.
    static let byName: [String: [LivingIconSource]] = [`);
for (const [file, prop] of FILES) out.push(`        "${file}": ${prop},`);
out.push('    ]');
for (const [file, prop] of FILES) {
  out.push('');
  out.push(`    // prototype/assets/icons/${file}.svg`);
  out.push(`    static let ${prop}: [LivingIconSource] = [`);
  out.push(...svgSources(file));
  out.push('    ]');
}
out.push('}');
process.stdout.write(out.join('\n') + '\n');
